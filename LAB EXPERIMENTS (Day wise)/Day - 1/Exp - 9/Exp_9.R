# AIM:
# To calculate the Interquartile Range (IQR) and Standard Deviation (SD) for car speeds
# under regular driving style.

# Car speeds dataset (regular driving style)
v <- c(78.3, 81.8, 82, 74.2, 83.4, 84.5, 82.9, 77.5, 80.9, 70.6)

# Calculate Interquartile Range (IQR = Q3 - Q1)
IQR(v)

# Calculate Standard Deviation (SD)
sd(v)
